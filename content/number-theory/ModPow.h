#pragma once

const long long mod = 1000000007; // faster if const

long long modpow(long long b, long long e) {
	long long ans = 1;
	for (; e; b = b * b % mod, e /= 2)
		if (e & 1) ans = ans * b % mod;
	return ans;
}
